// ============================================================================
// 题号剥离（v4.13.2）
// ============================================================================
//
// 【需求来源】
//   用户原话：「加一个功能 就是切完题后自动把序号去除（小题的不要去）」
//   追问后确认：**阿拉伯数字题号 + 中文大题号都去掉**，但更下级的
//   「小问号」（(1) / ① / （一））要保留。
//
// 【为什么要单独一个模块】
//   「导入」与「原卷编辑」两条入口必须给出**完全一致的**题号处理结果
//   （铁律#11 的同一思路：同一件事只允许一份实现）。
//   两份手写正则迟早会漂移，所以抽到这里共用。
//
// 【去 / 不去 一览】
//   ✅ 去：`1. ` `1、` `1）` `1．` `1 ）`（含全角 `１．`）
//          `一、` `二.` `（一）` `【一】`
//          `第1部分` `第一部分` `第Ⅰ卷` `第I卷`
//          `第1题` `第 1 题`
//   ❌ 不去：`(1)` `（1）` `①` `1）` 这类**小问号**
//            —— 注意 `(1)` 与 `1）` 的区分见下方「易混淆点」
//            `A.` `B、`（选项行，本就是独立字段）
//
// ---------------------------------------------------------------------------
// 【易混淆点：`(1)` 与 `1）` 到底谁是小问号？】
//
// 这是本功能最容易做错的地方，必须说清判据：
//   · `1.` `1、` `1．` —— 后接「顿号/点号」 → 是**题目序号**（去）
//   · `1）` `(1)` `（1）` —— 被**括号包裹** → 是**小问号**（不去）
//
// 依据：中文试卷排版惯例里，题目序号用「点/顿号」，小问用「括号」。
//   1. 下列说法正确的是（ ）      ← 题目序号，去
//     (1) 若 x>0，求……           ← 小问，保留
//  如果把 `(1)` 也当题号剥掉，用户会**永久丢失「这是第几小问」的信息**，
//   且这类小问在解答题里极常见 —— 所以宁可保守。
//
// ⚠️ 例外：`1）` 这种"半括号"在**题首且题目尚未进入小问语境**时，多数是题号。
//   但实测语料里 `1）` 既可能当题号也可能当小问（尤其解答题里 `1）2）3）` 连排）。
//   由于无法可靠区分，**统一按"括号类一律保留"处理**，保证不误删小问。
// ---------------------------------------------------------------------------

/**
 * 允许出现在题号与正文之间的空白/分隔符。
 * 含全角空格 U+3000、不换行空格 U+00A0 —— Word 里极常见。
 */
const SP = `[\\s\\u00a0\\u3000]*`

/**
 * 各级题号的匹配式（**均不含正文，只匹配题号本身**）。
 *
 * 顺序有讲究：**长的、具体的放前面**，避免 `第Ⅰ卷` 被 `一、` 之类截胡。
 */
const PATTERNS: RegExp[] = [
  // ① 「第Ⅰ卷」「第I卷」「第1部分」「第一部分」「第 2 卷」
  //    罗马数字 Ⅰ-Ⅻ（U+2160-216B）、Ⅰ 的全角变体，以及 V/X/L/C/D/M
  new RegExp(
    `^${SP}第${SP}[0-9０-９一二三四五六七八九十百IVXLCDMⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩⅪⅫ①②③④⑤⑥⑦⑧⑨⑩]${SP}[部卷]${SP}[分]?${SP}`,
  ),
  // ② 「第1题」「第 12 题」
  new RegExp(`^${SP}第${SP}[0-9０-９]{1,3}${SP}题${SP}`),
  // ③ 阿拉伯数字题号：「1.」「1、」「1．」「12.」「１．」（全角）
  //    ⚠️ 只认「点/顿号」，不认「括号」—— 括号是小问，见文件头说明
  //
  //    ⚠️⚠️「点号后紧跟数字 = 小数」这条判据**只对「点」生效，顿号不适用**：
  //        · 顿号 `、` 永远不是小数点 → `2、3个选项` 里 `2、` 就是题号
  //        · 点号 `.` `．` 后紧跟数字 → 小数（`1.5`、`3.14`），不剥
  //        实测踩过的坑：`1.5 倍的增长` 曾被剥成 `5 倍的增长`，直接毁题干。
  //
  //    点号后**有空格**时仍视为题号：`1. 5倍的增长` → 剥出 `5倍的增长`。
  //    点号后无空格且非数字时也是题号：`1.下列` → 剥出 `下列`。
  new RegExp(`^${SP}[0-9０-９]{1,3}${SP}(?:[.．](?![0-9０-９])|[、])${SP}`),
  // ④ 中文数字大题号：「一、」「二.」「十二、」
  new RegExp(`^${SP}[一二三四五六七八九十百零]{1,3}${SP}[、．.]${SP}`),
  // ⑤ 中文数字 + 括号：「（一）」「【一】」（**仅中文数字**，阿拉伯数字的括号是小问）
  new RegExp(`^${SP}[（(【]${SP}[一二三四五六七八九十百零]{1,3}${SP}[)）】]${SP}`),
  // ⑥ 裸中文数字大题号（无标点）：「一 选择题」—— 仅当后面不是顿号时
  //    保守起见只在明确是「选择/填空/判断/解答/计算/应用/简答/实验/作图」等题型词前生效
  new RegExp(`^${SP}[一二三四五六七八九十]{1,2}${SP}(?=[选填判解计应简实作])`),
]

/**
 * 会被误伤的前导符号：题号剥掉后，若正文以这些开头，一并清掉多余空白。
 * 例如 `1.（1）求……` → 剥掉 `1.` 后是 `（1）求……`（正确，保留小问）
 */
const LEAD_TRIM = /^[\s\u00a0\u3000]+/

/**
 * 剥离字符串开头的题号。
 *
 * @param text 待处理文本（**纯文本**，不含标签）
 * @returns    去掉题号后的文本
 */
export function stripNumberFromText(text: string): string {
  let s = String(text ?? '')
  if (!s) return s
  // 【v4.13.6 关键修正 · 只剥一轮】
  //
  // 旧实现最多剥**两轮**，本意是应对 `1. （1）求…` 这种「题号 + 小问」。
  // 但那是个**误判**：`（1）` 不匹配任何 PATTERN，第一轮剥掉 `1.` 之后
  // 循环本来就会自然停住 —— 第二轮**永远只在"正文开头又长了一个题号"时**生效，
  // 而那恰恰说明**第二个是正文，不该剥**。
  //
  // 🐞 实测踩中的坑（用户卷子「1. 第1题：已知集合运算…」）：
  //   第 1 轮：③ 剥掉 `1. `        → `第1题：已知集合运算…`
  //   第 2 轮：② 又剥掉 `第1题`     → `：已知集合运算…`   ← 正文被吃掉！
  //   用户看到题干变成「：已知集合运算」（开头整段丢失）。
  //
  // 所以：**题号只可能是题干开头的那一个**，剥一次即可。
  let hit = false
  for (const re of PATTERNS) {
    if (re.test(s)) {
      s = s.replace(re, '').replace(LEAD_TRIM, '')
      hit = true
      break
    }
  }
  // `hit` 仅供调试/将来扩展（当前无分支依赖），保留赋值避免 lint 报未使用
  void hit
  return s
}

/**
 * 剥离**题干 HTML 开头**的题号，保留其后所有标签（表格/图片/小问）。
 *
 * 【为什么不能直接对 HTML 用文本正则】
 *   题干是 HTML（含 `<p>` `<img>` `<table>`），题号可能：
 *     · 在第一个块级标签**内部**：`<p>1. 下列说法</p>`
 *     · 在标签**外面**：`1. <p>下列说法</p>`（少见但存在）
 *     · 被 `<strong>` 等行内标签**包裹**：`<p><strong>1.</strong> 说法</p>`
 *   所以要把「标签」与「文本」揉在一起的头部先找出来处理。
 *
 * 【实现策略】
 *   只在**开头这一小段**（题号不可能很长）里查找并替换：
 *     ① 跳过开头的块级开标签，找到第一段文本
 *     ② 若第一段文本就是题号 → 从原文里删掉这一段
 *     ③ 若题号跨标签（`<strong>1.</strong>`）→ 把标签内的文本替换掉
 *   超过一段仍未命中 → 判定「无题号」，**原样返回**（宁可不剥，不能乱剥）。
 *
 * @param html 题干 HTML
 * @returns    去掉开头题号后的 HTML
 */
export function stripQuestionNumber(html: string): string {
  const src = String(html ?? '')
  if (!src) return src

  // 快路径：完全不含标签 → 直接走文本逻辑
  if (!/<[a-z][^>]*>/i.test(src)) return stripNumberFromText(src)

  // ① 末尾可能有的空白/换行先记着，处理完再拼回去，避免破坏排版
  // ② 逐段扫描开头的「标签 / 文本」序列
  const parts: { type: 'tag' | 'text'; raw: string; index: number }[] = []
  const re = /<[^>]+>|(?:[^<]+)/g
  let m: RegExpExecArray | null
  while ((m = re.exec(src))) {
    parts.push({ type: m[0].startsWith('<') ? 'tag' : 'text', raw: m[0], index: m.index })
    // 只看开头一小段就够了（题号最多几十字符）
    if (m.index > 200) break
  }

  // ② 在开头序列里找第一段「有可见文字」的文本节点
  let textIdx = -1
  for (let i = 0; i < parts.length; i++) {
    const q = parts[i]
    if (q.type === 'text' && q.raw.trim()) { textIdx = i; break }
    // 遇到 <img> / <table> 等实体内容 → 说明前面没有题号了
    if (q.type === 'tag' && /^<(img|table|figure)\b/i.test(q.raw)) return src
  }
  if (textIdx < 0) return src

  const p = parts[textIdx]
  const stripped = stripNumberFromText(p.raw)
  if (stripped === p.raw) return src   // 没剥掉任何东西 → 原样返回

  // ③ 只替换那一段文本，其余原样保留
  const before = src.slice(0, p.index)
  const after = src.slice(p.index + p.raw.length)
  let out = before + stripped + after

  // ④ 清理剥号后残留在开头的**空行内标签**（`<strong></strong>` 等）。
  //    题号常被 Word 加粗（`<p><strong>1.</strong> 说法…</p>`），剥掉 "1." 后
  //    标签会留下 —— 富文本编辑器里成了"看不见却存在"的格式残留。
  //    只清理**无属性**的纯格式标签，避免误删 `<span class="…">` 这类必需要素。
  const EMPTY_INLINE = /^((?:\s*<(?:p|div)\b[^>]*>\s*)?)(?:(?:<(?:strong|b|em|i|u|span)\s*>(?:\s|&nbsp;)*<\/(?:strong|b|em|i|u|span)\s*>)\s*)+/i
  out = out.replace(EMPTY_INLINE, (_m, blockOpen: string) => blockOpen || '')
  return out
}

/**
 * 判断文本是否**以题号开头**（不修改内容）。
 * 供 UI 显示「该题仍带题号」提示、以及按钮的"有无可处理项"判断使用。
 */
export function hasLeadingNumber(text: string): boolean {
  const s = String(text ?? '').replace(/<[^>]*>/g, '')
  if (!s.trim()) return false
  return stripNumberFromText(s) !== s
}

